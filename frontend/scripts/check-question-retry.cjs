const assert = require('node:assert/strict');
const { buildSync } = require('esbuild');
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const path = require('node:path');
const compiled = buildSync({ absWorkingDir: path.resolve(__dirname, '..'), entryPoints: ['src/App.jsx'], bundle: true, write: false, platform: 'node', format: 'cjs', jsx: 'automatic', loader: { '.css': 'empty' }, external: ['react', 'react/jsx-runtime'] }).outputFiles[0].text;
const moduleResult = { exports: {} };
new Function('require', 'module', 'exports', compiled)(require, moduleResult, moduleResult.exports);
const render = (result) => renderToStaticMarkup(React.createElement(moduleResult.exports.AnswerView, { question: '한옥은 무엇인가요?', level: 'general', result, onAsk() {} }));
const insufficient = render({ response_type: 'insufficient_evidence', message: '근거가 부족합니다.', citations: [] });
assert.match(insufficient, /다시 검색할 질문/);
assert.match(insufficient, /한옥은 무엇인가요\?<\/textarea>/);
assert.match(insufficient, /다른 질문으로 찾아보기/);
assert.doesNotMatch(insufficient, /<h2>함께 알아보기/);
const clarification = render({ response_type: 'needs_clarification', message: '어느 궁궐인가요?', clarification: { options: [{ id: 'a', label: '경복궁' }] } });
assert.match(clarification, /경복궁<\/button>/);
assert.match(clarification, /이 질문으로 다시 검색/);
assert.doesNotMatch(clarification, /aria-label="함께 알아보기"/);
assert.doesNotMatch(render({ response_type: 'answered', message: '답변', citations: [] }), /다시 검색할 질문/);
console.log('PASS: insufficient evidence, clarification choices + free input, normal-answer separation');
